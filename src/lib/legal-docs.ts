export function legalDoc(key: LegalDocKey): LegalDocLink {
  const doc = LEGAL_DOCS.find((d) => d.key === key);
  if (!doc) throw new Error(`Unknown legal document: ${key}`);
  return doc;
}

/** The document after `key` in switcher order (wraps around). */
export function nextLegalDoc(key: LegalDocKey): LegalDocLink {
  const i = LEGAL_DOCS.findIndex((d) => d.key === key);
  return LEGAL_DOCS[(i + 1) % LEGAL_DOCS.length] ?? LEGAL_DOCS[0];
}

// ─── Portable Text helpers ────────────────────────────────────────────────────

/** Minimal structural view of a Portable Text body item. */
export interface LegalBlockLike {
  _type: string;
  _key?: string;
  style?: string;
  listItem?: string;
  children?: Array<{ _type?: string; text?: string; [k: string]: unknown }>;
  table?: { rows?: Array<{ cells?: string[] }> };
  [k: string]: unknown;
}

export type HeadingRank = 2 | 3 | 4;

export interface LegalHeading {
  /** Stable, slug-based anchor id. */
  id: string;
  /** Rendered heading level: the document's top level always renders as h2. */
  rank: HeadingRank;
  /** Number pill text ("3", "7.1"); null when the heading has none. */
  num: string | null;
  /** The separator after the number in the source ("." or ""), kept visually hidden. */
  numDot: string;
  /** Pill number generated by the template (not part of the source text). */
  generated: boolean;
  /** Heading text without the number prefix. */
  text: string;
}

export interface LegalTocItem {
  id: string;
  num: string | null;
  generated: boolean;
  text: string;
}

export interface PreparedLegalBody<T extends LegalBlockLike> {
  /** Body with the number prefix removed from numbered top-level headings. */
  body: T[];
  /** Heading meta keyed by block _key. */
  headings: Record<string, LegalHeading>;
  /** Top-level headings (h2, or h3 when the document has no h2). */
  toc: LegalTocItem[];
  words: number;
  minutes: number;
}

const HEADING_LEVEL: Record<string, number> = { h2: 2, h3: 3, h4: 4 };
const NUM_PREFIX = /^(\d+(?:\.\d+)*)(\.?)\s+(?=\S)/;

export function blockPlainText(block: LegalBlockLike): string {
  return (block.children ?? []).map((c) => (typeof c.text === "string" ? c.text : "")).join("");
}

function countWords(text: string): number {
  return text.trim().match(/\S+/g)?.length ?? 0;
}

/** Words in text blocks and table cells. */
export function legalWordCount(body: readonly LegalBlockLike[]): number {
  let words = 0;
  for (const block of body) {
    if (block._type === "block") words += countWords(blockPlainText(block));
    else if (block._type === "styledTable") {
      for (const row of block.table?.rows ?? []) {
        for (const cell of row.cells ?? []) words += countWords(cell ?? "");
      }
    }
  }
  return words;
}

/** "≈ N perc" at 200 words per minute, at least 1. */
export function legalReadingMinutes(words: number): number {
  return Math.max(1, Math.round(words / 200));
}

/** ASCII slug for anchor ids: "7.1. Általános rendelkezések" → "7-1-altalanos-rendelkezesek". */
export function slugifyHeading(text: string): string {
  const slug = text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80)
    .replace(/-+$/g, "");
  return slug || "fejezet";
}

/** Splits a leading "3." / "7.1." number off a heading. */
export function splitHeadingNumber(
  text: string,
): { num: string; dot: string; rest: string } | null {
  const m = NUM_PREFIX.exec(text);
  if (!m?.[1]) return null;
  return { num: m[1], dot: m[2] ?? "", rest: text.slice(m[0].length) };
}

/**
 * Derives heading ids / levels / number pills, the table of contents and the reading time.
 * The top level is h2, or h3 when the document has no h2 (then h3 → h2, h4 → h3).
 * Numbered top-level headings lose their number prefix in `body` (it moves to the pill) –
 * only when the prefix sits in the first span, otherwise the heading stays untouched.
 */
export function prepareLegalBody<T extends LegalBlockLike>(
  input: readonly T[] | null | undefined,
): PreparedLegalBody<T> {
  const source = input ?? [];
  const isHeading = (b: LegalBlockLike) =>
    b._type === "block" &&
    !b.listItem &&
    !!b.style &&
    b.style in HEADING_LEVEL &&
    blockPlainText(b).trim() !== "";
  const topStyle = source.some((b) => isHeading(b) && b.style === "h2") ? "h2" : "h3";
  const shift = topStyle === "h2" ? 0 : 1;
  const anyNumbered = source.some(
    (b) => isHeading(b) && b.style === topStyle && splitHeadingNumber(blockPlainText(b)) !== null,
  );

  const used = new Set<string>();
  const uniqueId = (base: string) => {
    let id = base;
    let n = 2;
    while (used.has(id)) id = `${base}-${n++}`;
    used.add(id);
    return id;
  };

  const headings: Record<string, LegalHeading> = {};
  const toc: LegalTocItem[] = [];

  let seenTop = false;
  const body = source.map((block, index) => {
    if (!isHeading(block)) return block;
    const level = HEADING_LEVEL[block.style ?? ""] ?? 4;
    const rank = Math.min(4, Math.max(2, level - shift)) as HeadingRank;
    // A sub-heading before the first top-level heading (e.g. the operator's name under
    // the title) would skip a level after the page h1: it renders as a bold paragraph.
    if (rank === 2) seenTop = true;
    else if (!seenTop) return block;
    const plain = blockPlainText(block);
    const key = block._key ?? `h-${index}`;
    const id = uniqueId(slugifyHeading(plain));

    let out: T = block;
    let num: string | null = null;
    let numDot = "";
    let generated = false;
    let text = plain;

    if (rank === 2) {
      const split = splitHeadingNumber(plain);
      const first = block.children?.[0];
      const prefixLength = split ? plain.length - split.rest.length : 0;
      if (split && typeof first?.text === "string" && first.text.length >= prefixLength) {
        num = split.num;
        numDot = split.dot;
        text = split.rest;
        out = {
          ...block,
          children: [
            { ...first, text: first.text.slice(prefixLength) },
            ...(block.children ?? []).slice(1),
          ],
        };
      } else if (!anyNumbered) {
        num = String(toc.length + 1);
        generated = true;
      }
      toc.push({ id, num, generated, text });
    }

    headings[key] = { id, rank, num, numDot, generated, text };
    return out;
  });

  const words = legalWordCount(source);
  return { body, headings, toc, words, minutes: legalReadingMinutes(words) };
}

/** Same rendering as the previous legal pages: "2026. július 21." (hu-HU, long month). */
export function formatLegalDate(value: string | null | undefined): string | null {
  if (!value) return null;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return null;
  return date.toLocaleDateString("hu-HU", { year: "numeric", month: "long", day: "numeric" });
}
